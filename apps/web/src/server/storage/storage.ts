/**
 * File storage for uploads (card art, later asset packs). The app only talks to this interface,
 * so the local-folder backend can be swapped for MinIO/S3 through configuration
 * (design/SPEC.md, section 2).
 */
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';

export interface StoredFile {
  readonly data: Buffer;
  readonly contentType: string;
}

export interface FileStorage {
  put(key: string, data: Buffer, contentType: string): Promise<void>;
  /** Returns null if there is no file under `key`. */
  get(key: string): Promise<StoredFile | null>;
  /** Deletes one file; missing files are ignored. */
  delete(key: string): Promise<void>;
  /** Deletes every file under a folder, e.g. "cards/<id>"; a missing folder is ignored. */
  deleteFolder(folder: string): Promise<void>;
}

/** Keys are generated by the server, but they also arrive in URLs, so they are checked strictly. */
const KEY_PATTERN = /^[a-z0-9][a-z0-9/_.-]*$/;

export function isValidStorageKey(key: string): boolean {
  return (
    KEY_PATTERN.test(key) &&
    !key.split('/').some((part) => part === '' || part === '.' || part === '..')
  );
}

const CONTENT_TYPES: Readonly<Record<string, string>> = {
  webp: 'image/webp',
  png: 'image/png',
  ttf: 'font/ttf',
  otf: 'font/otf',
};

/** Stores files under a directory on disk; the content type follows from the file extension. */
export function createLocalStorage(rootDir: string): FileStorage {
  const root = resolve(rootDir);

  const pathFor = (key: string): string => {
    if (!isValidStorageKey(key)) throw new RangeError(`Invalid storage key: ${key}`);
    const path = resolve(root, key);
    // Defence in depth: the key check already prevents escaping the root.
    if (!path.startsWith(root + sep)) throw new RangeError(`Storage key escapes the root: ${key}`);
    return path;
  };

  return {
    async put(key, data) {
      const path = pathFor(key);
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, data);
    },

    async get(key) {
      if (!isValidStorageKey(key)) return null;
      try {
        const data = await readFile(pathFor(key));
        const extension = key.slice(key.lastIndexOf('.') + 1);
        return { data, contentType: CONTENT_TYPES[extension] ?? 'application/octet-stream' };
      } catch (error) {
        if (error instanceof Error && 'code' in error && error.code === 'ENOENT') return null;
        throw error;
      }
    },

    async delete(key) {
      await rm(pathFor(key), { force: true });
    },

    async deleteFolder(folder) {
      await rm(pathFor(folder), { recursive: true, force: true });
    },
  };
}
