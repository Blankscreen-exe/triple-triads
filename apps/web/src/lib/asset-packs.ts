/**
 * Asset packs supply every image on a card face (design/SPEC.md, section 7). Each card is drawn
 * with its owner's pack.
 */

export interface AssetPackImages {
  readonly bgBlue: string;
  readonly bgRed: string;
  readonly frame: string;
  readonly cardBack: string;
  readonly digits: string;
  readonly elements: string;
  readonly stars: string;
}

export interface AssetPack {
  readonly id: string;
  readonly name: string;
  readonly images: AssetPackImages;
  /** Font for card names, loaded with @font-face; null uses the theme's display font. */
  readonly font: { readonly family: string; readonly url: string } | null;
}

